import 'dart:io';

import 'package:excel/excel.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:path_provider/path_provider.dart';

class ExportFileService {
  static const _channel = MethodChannel('com.easeinn.mobile/downloads');

  static const xlsxMimeType =
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

  static Uint8List createWorkbook({
    required String csvData,
    required String reportTitle,
    required String hotelName,
    required String selectedPeriod,
    required int recordCount,
    String? additionalDetails,
  }) {
    final rows = _parseCsv(csvData);
    if (rows.isEmpty)
      throw const FormatException('The export has no table data.');

    final excel = Excel.createExcel();
    excel.rename('Sheet1', 'Register');
    final sheet = excel['Register'];
    final columns = rows.first.length;
    if (columns == 0) throw const FormatException('The export has no columns.');
    final now = DateTime.now();

    _mergeMetadataRow(
      sheet,
      columns,
      0,
      'EaseInn™ | $reportTitle',
      CellStyle(
        bold: true,
        fontSize: 18,
        fontColorHex: _color('#FFFFFF'),
        backgroundColorHex: _color('#0F172A'),
        verticalAlign: VerticalAlign.Center,
      ),
    );
    _mergeMetadataRow(
      sheet,
      columns,
      1,
      'Hotel: $hotelName',
      _metadataStyle('#E8F7F1'),
    );
    _mergeMetadataRow(
      sheet,
      columns,
      2,
      'Selected period: $selectedPeriod',
      _metadataStyle('#F1F5F9'),
    );
    _mergeMetadataRow(
      sheet,
      columns,
      3,
      'Records: $recordCount',
      _metadataStyle('#E8F7F1'),
    );
    _mergeMetadataRow(
      sheet,
      columns,
      4,
      'Exported: ${_dateTimeLabel(now)}${additionalDetails == null ? '' : '  |  $additionalDetails'}',
      _metadataStyle('#F1F5F9'),
    );
    _mergeMetadataRow(
      sheet,
      columns,
      5,
      'Generated by EaseInn™ PMS',
      CellStyle(
        italic: true,
        fontSize: 9,
        fontColorHex: _color('#475569'),
        backgroundColorHex: _color('#FFFFFF'),
      ),
    );

    const headerRow = 7;
    final headerStyle = CellStyle(
      bold: true,
      fontColorHex: _color('#FFFFFF'),
      backgroundColorHex: _color('#059669'),
      textWrapping: TextWrapping.WrapText,
      verticalAlign: VerticalAlign.Center,
      horizontalAlign: HorizontalAlign.Center,
    );
    final bodyStyle = CellStyle(
      verticalAlign: VerticalAlign.Center,
      textWrapping: TextWrapping.WrapText,
      backgroundColorHex: _color('#FFFFFF'),
    );
    final alternateBodyStyle = CellStyle(
      verticalAlign: VerticalAlign.Center,
      textWrapping: TextWrapping.WrapText,
      backgroundColorHex: _color('#F8FAFC'),
    );

    for (var rowIndex = 0; rowIndex < rows.length; rowIndex++) {
      final values = rows[rowIndex];
      for (var columnIndex = 0; columnIndex < columns; columnIndex++) {
        final value = columnIndex < values.length ? values[columnIndex] : '';
        final cell = sheet.cell(
          CellIndex.indexByColumnRow(
            columnIndex: columnIndex,
            rowIndex: headerRow + rowIndex,
          ),
        );
        cell.value = TextCellValue(value);
        cell.cellStyle = rowIndex == 0
            ? headerStyle
            : rowIndex.isEven
            ? alternateBodyStyle
            : bodyStyle;
      }

      if (rowIndex == 0) {
        for (var columnIndex = 0; columnIndex < columns; columnIndex++) {
          final header = columnIndex < values.length ? values[columnIndex] : '';
          sheet.setColumnWidth(
            columnIndex,
            (header.length + 3).clamp(14, 34).toDouble(),
          );
        }
      }
    }

    sheet.setRowHeight(0, 30);
    sheet.setRowHeight(headerRow, 34);
    final encoded = excel.encode();
    if (encoded == null || encoded.isEmpty) {
      throw StateError('Could not generate the Excel workbook.');
    }
    return Uint8List.fromList(encoded);
  }

  static Future<void> saveToDownloads({
    required String fileName,
    required Uint8List bytes,
  }) async {
    if (!kIsWeb && Platform.isAndroid) {
      await _channel.invokeMethod<String>('saveToDownloads', {
        'fileName': fileName,
        'mimeType': xlsxMimeType,
        'bytes': bytes,
      });
      return;
    }

    if (kIsWeb) {
      throw UnsupportedError(
        'Use the browser download action for web exports.',
      );
    }
    final directory =
        await getDownloadsDirectory() ??
        await getApplicationDocumentsDirectory();
    final folder = Directory(
      '${directory.path}${Platform.pathSeparator}EaseInn',
    );
    await folder.create(recursive: true);
    await File(
      '${folder.path}${Platform.pathSeparator}$fileName',
    ).writeAsBytes(bytes, flush: true);
  }

  static CellStyle _metadataStyle(String fill) => CellStyle(
    bold: true,
    fontSize: 10,
    fontColorHex: _color('#1E293B'),
    backgroundColorHex: _color(fill),
    verticalAlign: VerticalAlign.Center,
  );

  static void _mergeMetadataRow(
    Sheet sheet,
    int columns,
    int row,
    String value,
    CellStyle style,
  ) {
    final lastColumn = columns - 1;
    if (lastColumn > 0) {
      sheet.merge(
        CellIndex.indexByColumnRow(columnIndex: 0, rowIndex: row),
        CellIndex.indexByColumnRow(columnIndex: lastColumn, rowIndex: row),
        customValue: TextCellValue(value),
      );
    } else {
      sheet
          .cell(CellIndex.indexByColumnRow(columnIndex: 0, rowIndex: row))
          .value = TextCellValue(
        value,
      );
    }
    for (var column = 0; column < columns; column++) {
      final cell = sheet.cell(
        CellIndex.indexByColumnRow(columnIndex: column, rowIndex: row),
      );
      if (column == 0) cell.value = TextCellValue(value);
      cell.cellStyle = style;
    }
  }

  static List<List<String>> _parseCsv(String input) {
    final rows = <List<String>>[];
    var row = <String>[];
    final field = StringBuffer();
    var inQuotes = false;
    final text = input.startsWith('\uFEFF') ? input.substring(1) : input;

    for (var i = 0; i < text.length; i++) {
      final char = text[i];
      if (char == '"') {
        if (inQuotes && i + 1 < text.length && text[i + 1] == '"') {
          field.write('"');
          i++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (char == ',' && !inQuotes) {
        row.add(field.toString());
        field.clear();
      } else if ((char == '\n' || char == '\r') && !inQuotes) {
        if (char == '\r' && i + 1 < text.length && text[i + 1] == '\n') i++;
        row.add(field.toString());
        field.clear();
        if (row.any((value) => value.isNotEmpty)) rows.add(row);
        row = <String>[];
      } else {
        field.write(char);
      }
    }
    if (field.length > 0 || row.isNotEmpty) {
      row.add(field.toString());
      if (row.any((value) => value.isNotEmpty)) rows.add(row);
    }
    return rows;
  }

  static String _dateTimeLabel(DateTime value) =>
      '${value.year.toString().padLeft(4, '0')}-${value.month.toString().padLeft(2, '0')}-${value.day.toString().padLeft(2, '0')} ${value.hour.toString().padLeft(2, '0')}:${value.minute.toString().padLeft(2, '0')}';

  static ExcelColor _color(String value) =>
      ExcelColor.fromHexString('FF${value.replaceFirst('#', '')}');
}
